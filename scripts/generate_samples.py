"""Generate deterministic, inert Ethernet captures from documentation addresses."""
import hashlib
import json
import socket
import struct
from pathlib import Path

from app.catalog import CAPTURES, RULES, STATIC
from app.services.pipeline import build_report


def checksum(data):
    data += b"\0" * (len(data) % 2)
    total = sum(struct.unpack(f"!{len(data) // 2}H", data))
    while total >> 16:
        total = (total & 65535) + (total >> 16)
    return ~total & 65535


def ethernet_frame(src, dst, sport, dport, body):
    source, destination = socket.inet_aton(src), socket.inet_aton(dst)
    flags = 0x18 if body else 0x02
    tcp = struct.pack("!HHIIBBHHH", sport, dport, 1, int(bool(body)), 0x50, flags, 8192, 0, 0)
    pseudo = source + destination + struct.pack("!BBH", 0, 6, 20 + len(body))
    tcp = tcp[:16] + struct.pack("!H", checksum(pseudo + tcp + body)) + tcp[18:]
    ip = struct.pack("!BBHHHBBH4s4s", 0x45, 0, 40 + len(body), sport, 0, 64, 6, 0, source, destination)
    ip = ip[:10] + struct.pack("!H", checksum(ip)) + ip[12:]
    return bytes.fromhex("0200000000020200000000010800") + ip + tcp + body


def generate():
    CAPTURES.mkdir(exist_ok=True)
    demos = {}
    for rule, count in zip(RULES, (12, 3, 8), strict=True):
        sample = rule["sample"]
        packets = bytearray(struct.pack("<IHHIIII", 0xa1b2c3d4, 2, 4, 0, 0, 65535, 1))
        matches = {row["id"]: [] for row in RULES}
        for index in range(count + 4):
            signal = index < count
            source, destination = ("192.0.2.18", "198.51.100.42") if sample == "ransomware" else ("203.0.113.24", "192.0.2.80")
            dport, path, agent = 80, "/status", "fixture"
            if signal and sample == "ransomware":
                path, agent = "/gate.php", "Lab MSIE indicator"
            elif signal and sample == "sqli":
                path = "/catalog?label=SELECT"
            elif signal and sample == "ssh":
                dport = 22
            # Vary innocuous metadata lengths so the frame-size trace has visible structure.
            marker = "x" * ((index * 29) % 97)
            body = f"GET {path} HTTP/1.1\r\nHost: sample.invalid\r\nUser-Agent: {agent}\r\nX-Fixture-Tag: {marker}\r\n\r\n".encode() if dport == 80 else b""
            port = 42000 + index
            packet = ethernet_frame(source, destination, port, dport, body)
            timestamp = 1780430400 + index * 3
            packets.extend(struct.pack("<IIII", timestamp, 0, len(packet), len(packet)) + packet)
            if signal:
                matches[rule["id"]].append({"frame": index + 1, "source": source, "destination": destination,
                    "time": timestamp, "port": port, "protocol": rule["protocol"], "bytes": len(packet)})
        (CAPTURES / rule["file"]).write_bytes(packets)
        report = build_report(rule["file"], "Fixture replay", count + 4, matches, allow_model=False)
        demos[sample] = {"title": rule["short"], "description": rule["summary"],
            "sha256": hashlib.sha256(packets).hexdigest(), "size": len(packets), "report": report}
    (STATIC / "demo-data.js").write_text("// Generated by python -m scripts.generate_samples\n"
        + "window.SENTINEL_DEMOS = " + json.dumps(demos, indent=2) + ";\n")
    (CAPTURES / "fixtures.json").write_text(json.dumps(demos, indent=2) + "\n")


if __name__ == "__main__":
    generate()
